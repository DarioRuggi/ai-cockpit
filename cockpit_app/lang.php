// =============================================================================
// lang.php — UI language packs for the Cockpit app itself.
//
//   GET ?action=list            → [{code,name,native,dir,coverage,hash,source}, …]
//   GET ?action=get&code=he     → {_meta, strings:{key:"text"}}   (pack + your overrides)
//   GET ?action=template        → the empty template, as a download
//   GET ?action=template&code=he→ the template FILLED with that language's current translation (the missing strings are the empty ones)
//   GET ?action=strings&code=xx → everything the Translation Studio needs: {en:{key:English}, mine:{key:text}, meta}
//   POST ?action=check          → validate a pack ({code, meta, strings}) without writing; answers the problems per key
//   GET  ?action=models         → the models your local Ollama has, best translator first (signed in)
//   POST ?action=auto           → AutoTranslate: {keys:[…≤12], lang_name, code, model} → drafts from a local model, each checked against the English placeholders (signed in)
//   POST ?action=save           → validate and write <cockpit data>/lang/<code>.json (needs a signed-in writer; everything above stays public)
//
// Deliberately NOT behind auth.php. The login screen needs its language before
// anyone is signed in, and this serves nothing but translations (like edition.php
// it answers before a session exists). js/head.js exempts it from the request gate
// for the same reason.
//
// Two places are read, and a key from the second wins:
//   1. <app>/lang/*.json              shipped with Cockpit (root-owned, replaced on update)
//   2. <cockpit_data root>/lang/*.json   YOURS. A language Cockpit does not ship, or a
//                                      correction to one it does. Survives updates.
//
// Why not just drop a file into <app>/lang/? The installer makes the shipped files
// root-owned and read-only, and cockpit-guard puts back anything that changes or is
// added there — so a file added to the web root would be reverted. The data folder is
// yours and is never touched by an update.
//
// A pack is { "_meta": {code,name,native,dir,translator,…}, "strings": {key: text} }.
// English is not served as a pack at runtime: the English text lives IN the code, as
// the fallback argument of T('key', 'English') and the content of data-i18n elements.
// en.json exists for translators and is generated by Installs/lang_extract.php.
// =============================================================================
require_once __DIR__ . '/paths.php';
if (session_status() === PHP_SESSION_ACTIVE) session_write_close();   // read-only; never hold the session lock

header('Content-Type: application/json; charset=utf-8');
header('Cache-Control: no-cache');

$SHIPPED = __DIR__ . '/lang';
$MINE    = rtrim((string)($PATHS['cockpit_data_root'] ?? ''), '/') . '/lang';

/** A language code: "he", "pt-BR", "yue". Anything else never reaches the filesystem. */
function lang_code_ok(string $c): bool { return (bool)preg_match('/^[a-z]{2,3}(-[A-Za-z0-9]{2,8})?$/', $c); }

function lang_read(string $f): ?array {
    if (!is_file($f)) return null;
    $j = json_decode((string)@file_get_contents($f), true);
    return is_array($j) ? $j : null;
}
function lang_filled(array $strings): array {         // drop untranslated (empty) entries
    return array_filter($strings, fn($v) => is_string($v) && trim($v) !== '');
}
function lang_files(string $dir): array {
    $out = [];
    foreach ((glob($dir . '/*.json') ?: []) as $f) {
        $code = basename($f, '.json');
        if ($code[0] === '_' || !lang_code_ok($code)) continue;     // _template.json and friends
        $out[$code] = $f;
    }
    return $out;
}
/** The shipped pack with your overrides laid over it. */
function lang_merged(string $code, string $SHIPPED, string $MINE): ?array {
    $a = lang_read("$SHIPPED/$code.json"); $b = lang_read("$MINE/$code.json");
    if (!$a && !$b) return null;
    $meta = array_merge((array)($a['_meta'] ?? []), (array)($b['_meta'] ?? []));
    $meta['code'] = $code;
    $strings = lang_filled((array)($a['strings'] ?? [])) ;
    foreach (lang_filled((array)($b['strings'] ?? [])) as $k => $v) $strings[$k] = $v;
    ksort($strings);
    return ['_meta' => $meta, 'strings' => $strings, '_source' => ($a ? 'shipped' : '') . ($a && $b ? '+' : '') . ($b ? 'yours' : '')];
}

$action = (string)($_GET['action'] ?? 'list');

// ── Translation Studio helpers ────────────────────────────────────────────────────────────────
/** The {placeholders} of a string, sorted: a translation must carry exactly the English ones. */
function lang_placeholders(string $s): array { preg_match_all('/\{[A-Za-z0-9_]+\}/', $s, $m); $a = $m[0]; sort($a); return $a; }
/** Check a pack as sent by the Studio or an uploaded file. → [clean pack, problems per key, general problems]. Nothing here touches the disk. */
function lang_check(array $in, array $en): array {
    $gen = []; $bad = [];
    $code = (string)($in['code'] ?? ($in['_meta']['code'] ?? ''));
    if (!lang_code_ok($code))  $gen[] = 'The language code must look like he, fr or pt-BR.';
    if ($code === 'en')        $gen[] = 'English is the base language and cannot be replaced.';
    $m = (array)($in['meta'] ?? ($in['_meta'] ?? []));
    $meta = ['code' => $code,
        'name'       => mb_substr(trim((string)($m['name'] ?? '')), 0, 80),
        'native'     => mb_substr(trim((string)($m['native'] ?? '')), 0, 80),
        'dir'        => (($m['dir'] ?? 'ltr') === 'rtl') ? 'rtl' : 'ltr',
        'mirror'     => ((($m['dir'] ?? 'ltr') === 'rtl') && !empty($m['mirror'])),   // right-to-left only: also mirror the layout (sidebars, strips)?
        'translator' => mb_substr(trim((string)($m['translator'] ?? '')), 0, 120)];
    if ($meta['name'] === '')   $gen[] = 'Give the language its English name.';
    if ($meta['native'] === '') $meta['native'] = $meta['name'];
    $clean = []; $unknown = 0;
    foreach ((array)($in['strings'] ?? []) as $k => $v) {
        if (!is_string($k) || !is_string($v)) continue;
        if (substr($k, -3) === '#en') continue;                       // the English hint lines of a downloaded template
        $v = trim($v); if ($v === '') continue;
        if (!isset($en[$k])) { $unknown++; continue; }               // a key Cockpit does not have (an older file): left out
        if (mb_strlen($v) > 4000)                                   { $bad[$k] = 'Longer than 4000 characters.'; continue; }
        if (preg_match('/[\x00-\x08\x0B\x0C\x0E-\x1F]/', $v))    { $bad[$k] = 'Contains a control character.'; continue; }
        if (lang_placeholders($v) !== lang_placeholders((string)$en[$k])) {
            $want = lang_placeholders((string)$en[$k]);
            $bad[$k] = 'The placeholders must stay exactly as in English: ' . ($want ? implode(' ', $want) : '(none)') . '.'; continue;
        }
        $clean[$k] = $v;
    }
    ksort($clean);
    return ['pack' => ['_meta' => $meta, 'strings' => $clean], 'bad' => $bad, 'general' => $gen, 'unknown' => $unknown];
}
function lang_json_in(): array { $j = json_decode((string)file_get_contents('php://input'), true); return is_array($j) ? $j : []; }
function lang_en_strings(string $SHIPPED): array { $e = lang_read("$SHIPPED/en.json"); return (array)($e['strings'] ?? []); }

if ($action === 'list') {
    $en = lang_read("$SHIPPED/en.json");
    $total = max(1, count((array)($en['strings'] ?? [])));
    $codes = array_unique(array_merge(array_keys(lang_files($SHIPPED)), array_keys(lang_files($MINE))));
    $rows = [];
    foreach ($codes as $code) {
        $p = lang_merged($code, $SHIPPED, $MINE); if (!$p) continue;
        $n = count($p['strings']);
        $m = $p['_meta'];
        $rows[] = [
            'code'     => $code,
            'name'     => (string)($m['name'] ?? $code),
            'native'   => (string)($m['native'] ?? ($m['name'] ?? $code)),
            'dir'      => (($m['dir'] ?? 'ltr') === 'rtl') ? 'rtl' : 'ltr',
            'coverage' => $code === 'en' ? 100 : (int)round(100 * $n / $total),
            'hash'     => substr(md5(json_encode($p['strings'])), 0, 12),
            'source'   => $p['_source'],
        ];
    }
    usort($rows, function ($a, $b) {                   // English first, then by native name
        if ($a['code'] === 'en') return -1; if ($b['code'] === 'en') return 1;
        return strcasecmp($a['native'], $b['native']);
    });
    echo json_encode(['ok' => true, 'languages' => $rows, 'folder' => $MINE], JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES);
    exit;
}

if ($action === 'get') {
    $code = (string)($_GET['code'] ?? '');
    if (!lang_code_ok($code)) { http_response_code(400); echo json_encode(['ok' => false, 'error' => 'Bad language code']); exit; }
    $p = lang_merged($code, $SHIPPED, $MINE);
    if (!$p) { http_response_code(404); echo json_encode(['ok' => false, 'error' => 'No such language']); exit; }
    $p['ok'] = true; $p['_meta']['hash'] = substr(md5(json_encode($p['strings'])), 0, 12);
    echo json_encode($p, JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES);
    exit;
}

if ($action === 'template') {
    $t = @file_get_contents("$SHIPPED/_template.json");
    if ($t === false) { http_response_code(404); echo json_encode(['ok' => false, 'error' => 'No template']); exit; }
    $code = (string)($_GET['code'] ?? '');
    $p = ($code !== '' && lang_code_ok($code)) ? lang_merged($code, $SHIPPED, $MINE) : null;
    if ($p) {                                           // the template with what this language already has filled in: only the empty ones are left to do
        $j = json_decode($t, true);
        if (is_array($j)) {
            $j['_meta'] = array_merge((array)$j['_meta'], (array)$p['_meta']);
            foreach ($p['strings'] as $k => $v) if (isset($j['strings'][$k])) $j['strings'][$k] = $v;
            $t = json_encode($j, JSON_PRETTY_PRINT | JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES);
        }
        header('Content-Disposition: attachment; filename="cockpit-' . $code . '-to-translate.json"');
    } else header('Content-Disposition: attachment; filename="cockpit-language-template.json"');
    echo $t;
    exit;
}

// ── AutoTranslate: a local model (Ollama) drafts the translation; nothing leaves the machine ─────────────────────────
function lang_ollama(string $path, ?array $body, int $timeout) {
    $ch = curl_init((getenv('COCKPIT_OLLAMA_URL') ?: 'http://127.0.0.1:11434') . $path);   // the env var lets a test point it at a stub
    $o = [CURLOPT_RETURNTRANSFER => 1, CURLOPT_TIMEOUT => $timeout, CURLOPT_CONNECTTIMEOUT => 3];
    if ($body !== null) { $o[CURLOPT_POST] = 1; $o[CURLOPT_HTTPHEADER] = ['Content-Type: application/json']; $o[CURLOPT_POSTFIELDS] = json_encode($body); }
    curl_setopt_array($ch, $o); $r = curl_exec($ch); $code = (int)curl_getinfo($ch, CURLINFO_HTTP_CODE); curl_close($ch);
    return ($r !== false && $code === 200) ? json_decode((string)$r, true) : null;
}
/** How good a model name is likely to be at translating (higher first); chat models only. */
function lang_model_score(string $n): int {
    $l = strtolower($n);
    if (preg_match('/embed|coder|r1|rerank|minicpm|vision|llava/', $l)) return -1;
    if (strpos($l, 'translate') !== false) return 100;
    if (strpos($l, 'aya') !== false) return 90;
    if (preg_match('/gemma3:(12|27)/', $l)) return 85;
    if (strpos($l, 'gemma3') !== false) return 80;
    if (preg_match('/qwen2\.5:(7|14|32)/', $l)) return 75;
    if (strpos($l, 'qwen') !== false) return 60;
    if (strpos($l, 'llama3') !== false) return 55;
    if (strpos($l, 'phi') !== false) return 40;
    return 30;
}
if ($action === 'models') {
    require_once __DIR__ . '/auth.php'; auth_require_writer();
    $t = lang_ollama('/api/tags', null, 4); $rows = [];
    foreach ((array)($t['models'] ?? []) as $m) { $sc = lang_model_score((string)$m['name']); if ($sc >= 0) $rows[] = ['name' => $m['name'], 'gb' => round(($m['size'] ?? 0) / 1e9, 1), 'score' => $sc]; }
    usort($rows, fn($a, $b) => $b['score'] <=> $a['score'] ?: $a['gb'] <=> $b['gb']);
    echo json_encode(['ok' => $t !== null, 'models' => $rows, 'error' => $t === null ? 'Ollama does not answer on this computer.' : null], JSON_UNESCAPED_UNICODE);
    exit;
}
if ($action === 'auto') {
    if ($_SERVER['REQUEST_METHOD'] !== 'POST') { http_response_code(405); echo json_encode(['ok' => false, 'error' => 'POST only']); exit; }
    require_once __DIR__ . '/auth.php'; auth_require_writer();
    $in = lang_json_in(); $en = lang_en_strings($SHIPPED);
    $model = (string)($in['model'] ?? ''); $code = (string)($in['code'] ?? ''); $name = trim((string)($in['lang_name'] ?? ''));
    $keys = array_values(array_filter((array)($in['keys'] ?? []), fn($k) => is_string($k) && isset($en[$k])));
    if (!preg_match('/^[A-Za-z0-9._:\/-]{1,80}$/', $model) || $keys === [] || count($keys) > 12) { echo json_encode(['ok' => false, 'error' => 'Choose a model and at most 12 lines.']); exit; }
    $label = $name !== '' ? $name . ($code !== '' ? " ($code)" : '') : $code;
    if ($label === '') { echo json_encode(['ok' => false, 'error' => 'Name the language first.']); exit; }
    $label = mb_substr(preg_replace('/[^\p{L}\p{N} ()._-]/u', '', $label), 0, 60);
    $lines = []; foreach ($keys as $i => $k) $lines[] = ($i + 1) . ' | ' . str_replace(["\r\n", "\n"], ' ⏎ ', (string)$en[$k]);
    $prompt = "You are a professional software localizer. Translate these user-interface texts of a desktop app from English into {$label}.\n" .
        "Rules: keep every {placeholder} (curly braces) exactly as written; do NOT translate product and file names (Cockpit, Ollama, Claude, Gemini, Codex, tmux, Library, .json, URLs) or keyboard keys; " .
        "keep the same punctuation, ellipsis (…) and the symbol ⏎ where it appears; use the natural, short wording a native speaker would see on a button; no explanations.\n" .
        "Answer with exactly one line per input line, in the same form as the input: the NUMBER, then \" | \", then ONLY the translation (never repeat the English).\n\n" . implode("\n", $lines);
    $res = lang_ollama('/api/generate', ['model' => $model, 'prompt' => $prompt, 'stream' => false, 'options' => ['temperature' => 0.2, 'num_predict' => 1800], 'keep_alive' => '10m'], 150);
    if (!is_array($res) || !isset($res['response'])) { echo json_encode(['ok' => false, 'error' => 'The local model did not answer (is Ollama running, and is the model installed?).']); exit; }
    $out = []; $rejected = [];
    foreach (preg_split('/\R/u', (string)$res['response']) as $ln) {
        if (!preg_match('/^\s*(\d+)\s*[|\t.:)\-]\s*(.+?)\s*$/u', $ln, $m)) continue;
        if (strpos($m[2], ' | ') !== false) $m[2] = trim(explode(' | ', $m[2])[0]);       // a model that repeats the English after a bar: keep the first part
        $i = (int)$m[1] - 1; if (!isset($keys[$i]) || isset($out[$keys[$i]])) continue;
        $k = $keys[$i]; $t = trim(str_replace(' ⏎ ', "\n", str_replace('⏎', "\n", $m[2])));
        if ($t === '' || mb_strlen($t) > 4000 || lang_placeholders($t) !== lang_placeholders((string)$en[$k]) || mb_strtolower($t) === mb_strtolower((string)$en[$k]) && !preg_match('/^[A-Z0-9 .\/+_-]+$/', $t)) { $rejected[] = $k; continue; }
        $out[$k] = $t;
    }
    foreach ($keys as $k) if (!isset($out[$k]) && !in_array($k, $rejected, true)) $rejected[] = $k;
    echo json_encode(['ok' => true, 'results' => (object)$out, 'rejected' => $rejected, 'model' => $model, 'seconds' => round((float)($res['total_duration'] ?? 0) / 1e9, 1)], JSON_UNESCAPED_UNICODE);
    exit;
}

if ($action === 'strings') {
    $code = (string)($_GET['code'] ?? '');
    if ($code !== '' && !lang_code_ok($code)) { http_response_code(400); echo json_encode(['ok' => false, 'error' => 'Bad language code']); exit; }
    $en = lang_en_strings($SHIPPED);
    $p  = $code !== '' ? lang_merged($code, $SHIPPED, $MINE) : null;
    echo json_encode(['ok' => true, 'en' => $en, 'mine' => $p ? $p['strings'] : (object)[], 'meta' => $p ? $p['_meta'] : (object)[],
        'source' => $p ? $p['_source'] : '', 'folder' => $MINE, 'writable' => (is_dir($MINE) ? is_writable($MINE) : is_writable(dirname($MINE)))], JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES);
    exit;
}

if ($action === 'check' || $action === 'save') {
    if ($_SERVER['REQUEST_METHOD'] !== 'POST') { http_response_code(405); echo json_encode(['ok' => false, 'error' => 'POST only']); exit; }
    require_once __DIR__ . '/auth.php';          // everything above answers before sign-in; writing needs a signed-in person who may write
    auth_require_writer();
    $r = lang_check(lang_json_in(), lang_en_strings($SHIPPED));
    $out = ['ok' => !$r['general'], 'general' => $r['general'], 'bad' => (object)$r['bad'], 'unknown_keys' => $r['unknown'], 'count' => count($r['pack']['strings'])];
    if ($action === 'save' && !$r['general']) {
        $code = $r['pack']['_meta']['code'];
        if (!is_dir($MINE) && !@mkdir($MINE, 0775, true)) { $out['ok'] = false; $out['general'][] = 'Cockpit cannot create the folder ' . $MINE . ' (permissions).'; }
        else {
            $tmp = "$MINE/.$code.json.tmp" . getmypid();
            $ok = @file_put_contents($tmp, json_encode($r['pack'], JSON_PRETTY_PRINT | JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES) . "\n") !== false && @rename($tmp, "$MINE/$code.json");
            if (!$ok) { @unlink($tmp); $out['ok'] = false; $out['general'][] = 'Cockpit cannot write ' . $MINE . '/' . $code . '.json (permissions).'; }
            else { @chmod("$MINE/$code.json", 0664); $out['saved'] = "$MINE/$code.json"; }
        }
    }
    echo json_encode($out, JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES);
    exit;
}

http_response_code(400);
echo json_encode(['ok' => false, 'error' => 'Unknown action']);
